# an f-string lets you embed variable values directly inside a string. put an f before the opening quote and write variables inside {}.

name = "suraj kumar"
age = 22

# using f-string
print(f"my name is {name} and i am {age} years old.")

# expressions inside f-string
print(f"next year i will be {age + 1} years old.")
print(f"5 + 3 = {5 + 3}")
