# what is a variable?
# a variable is a name that stores a value in memory. think of it as a labelled box: you give the box a name, put something inside, and refer to it whenever you need it.

name = "suraj kumar"
age = 22
gpa = 6.4
is_student = True

print(name, age, gpa, is_student)
print(name)
print(age)
print(gpa)
print(is_student)

# note: python does not require you to declare the type of variables. it figures it out automatically based on the value you assign.
