"""
comparison operators: compare two values and always return a boolean (either True or False).
equal to (==)             :       5 == 5 true
not equal to (!=)         :       5 != 3 true
greater than (>)          :       7 > 3  true
less than (<)             :       2 < 1  false
greater than or equal (>=):       5 >= 5 true
less than or equal (<=)   :       4 <= 3 false
"""

a = 10
b = 5
print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)
