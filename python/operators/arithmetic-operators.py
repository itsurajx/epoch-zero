"""
# arithmetic operators are used to perform basic mathematical operations.
addition(+):        10 + 3 = 13
subtraction(-):     10 - 3 = 7
multiplication(*):  10 * 3 = 30
division(/):        10/3 = 3.333...
floor division(//): 10//3 = 3 (rounds down to the nearest integer)
modulus(%):         10 % 3 = 1 (gives remainder)
exponentiation(**): 2**4 = 16  (2^4)
"""

print(f"addition(+)         :        {10 + 3}")
print(f"subtraction(-)      :        {10 - 3}")
print(f"multiplication(*)   :        {10 * 3}")
print(f"division(/)         :        {10 / 3}")
print(f"floor division(//)  :        {10 // 3}")
print(f"modulus(%)          :        {10 % 3}")
print(f"exponentiation(**)  :        {2 ** 4}")
